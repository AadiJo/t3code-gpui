// Writes apps/web/src/speech/language_names_data.rs: the name of each speech language code in
// each UI language, as `Intl.DisplayNames` gives it (the fork's `languageLabel`). The names come
// from the CLDR data in Node's ICU (Unicode License v3). Usage: node scripts/i18n/gen-language-names.mjs
import fs from "node:fs";

const out = new URL("../../apps/web/src/speech/language_names_data.rs", import.meta.url);
const source = fs.readFileSync(new URL("../../apps/web/src/speech/language_names.rs", import.meta.url), "utf8");
const list = source.slice(source.indexOf("SPEECH_LANGUAGE_CODES"));
const codes = [...list.slice(0, list.indexOf("];")).matchAll(/"([a-z]{2,3})"/g)].map((m) => m[1]);
const locales = ["en", "de", "es", "fr", "ja", "ko", "pt-BR", "ru", "sv", "zh"];
const quote = (s) => JSON.stringify(s);
let rust = `// @generated by scripts/i18n/gen-language-names.mjs from CLDR ${process.versions.cldr} (ICU ${process.versions.icu},\n`;
rust += `// Unicode License v3, https://www.unicode.org/license.txt). Do not edit.\n\n`;
rust += `/// The speech language codes, in the order of each row of [\`NAMES\`].\npub const CODES: [&str; ${codes.length}] = [${codes.map(quote).join(", ")}];\n\n`;
rust += `/// Each UI language's tag and its name for every code in [\`CODES\`].\npub const NAMES: [(&str, [&str; ${codes.length}]); ${locales.length}] = [\n`;
for (const locale of locales) {
  const names = new Intl.DisplayNames([locale], { type: "language" });
  rust += `    (${quote(locale)}, [${codes.map((code) => quote(names.of(code) ?? code)).join(", ")}]),\n`;
}
rust += "];\n";
fs.writeFileSync(out, rust);
console.log(`${codes.length} codes x ${locales.length} locales`);
